# 2. Add to existing NIDM file -> attaches to the existing Person
# ---------------------------------------------------------------------------


def test_add_to_existing_attaches_to_person(tmp_path: Path):
    # Build a tiny existing NIDM file: Project + Person "01".
    exp = Project(title="tiny experiment")
    existing_person = Person(exp, subject_id="01")
    orig_person_uri = URIRef(str(existing_person.identifier))
    existing_file = tmp_path / "experiment.ttl"
    exp.write(existing_file)

    measures = {"BrainSegVol": 1234567}
    cde = _build_cde(measures)

    graph = add_segmentation_derivative(
        subject_id="01",
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=cde,
        nidm_file=str(existing_file),
    )

    # No duplicate Person minted -- still exactly one, and it's the original.
    persons = list(graph.subjects(RDF.type, PROV.Person))
    assert persons == [orig_person_uri]

    # The derivative's subject association points at the EXISTING Person.
    der = _one(graph.subjects(RDF.type, NIDM["Derivative"]))
    subj_agents = set()
    for assoc in graph.objects(der, PROV.qualifiedAssociation):
        if SIO.Subject in set(graph.objects(assoc, PROV.hadRole)):
            subj_agents.update(graph.objects(assoc, PROV.agent))
    assert orig_person_uri in subj_agents


# ---------------------------------------------------------------------------
# 3. Cross-graph join (uber-graph query works across files)
# ---------------------------------------------------------------------------

# A predicate that lives ONLY in the experiment graph, so a query that
# returns it proves the derivative measure joined to the experiment subject.
AGE_AT_SCAN = NIDM["ageAtScan"]

# Join derivative volumes back to the experiment subject via
# ndar:src_subject_id, requiring the experiment-only ?age so a returned row
# can only come from BOTH files.
_JOIN_QUERY = """
    PREFIX prov: <http://www.w3.org/ns/prov#>
    PREFIX ndar: <https://ndar.nih.gov/api/datadictionary/v2/dataelement/>
    PREFIX nidm: <http://purl.org/nidash/nidm#>
    PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>

    SELECT DISTINCT ?ID ?volume ?age WHERE {
        ?der_act a nidm:Derivative ;
                 prov:qualifiedAssociation [ prov:agent ?subj ] .
        ?subj a prov:Person ;
              ndar:src_subject_id ?derID .
        ?der_obj prov:wasGeneratedBy ?der_act ;
                 ?measure ?volume .
        ?measure a/rdfs:subClassOf* nidm:DataElement ;
                 nidm:measureOf <http://uri.interlex.org/base/ilx_0112559> ;
                 nidm:datumType <http://uri.interlex.org/base/ilx_0738276> .
        ?exp_person a prov:Person ;
                    ndar:src_subject_id ?ID ;
                    nidm:ageAtScan ?age .
        FILTER( REPLACE(STR(?derID), "^0+", "") = REPLACE(STR(?ID), "^0+", "") )
    }
"""


def _experiment_graph(subject_id: str, age: int) -> Graph:
    """A separate experiment graph: Project + Person(subject_id) carrying an
    experiment-only nidm:ageAtScan (used to prove the cross-file join)."""
    exp = Project(title="experiment")
    person = Person(exp, subject_id=subject_id)
    exp.graph.add((person.identifier, AGE_AT_SCAN, Literal(age)))
    return exp.graph


def _uber_graph(derivative_graph: Graph, experiment_graph: Graph) -> Graph:
    """Load both graphs into one rdflib.Graph (as a triplestore would)."""
    uber = Graph()
    uber.parse(data=derivative_graph.serialize(format="turtle"), format="turtle")
    uber.parse(data=experiment_graph.serialize(format="turtle"), format="turtle")
    return uber


def test_cross_graph_join():
    measures = {"BrainSegVol": 1200000}
    cde = _build_cde(measures)

    derivative_graph = add_segmentation_derivative(
        subject_id="01",
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=cde,
        nidm_file=None,
    )
    experiment_graph = _experiment_graph(subject_id="01", age=42)

    uber = _uber_graph(derivative_graph, experiment_graph)
    rows = list(uber.query(_JOIN_QUERY))

    assert rows, "cross-graph join returned no rows"
    ids = {str(r["ID"]) for r in rows}
    ages = {int(r["age"]) for r in rows}
    volumes = {int(r["volume"]) for r in rows}
    assert ids == {"01"}
    assert ages == {42}
    assert 1200000 in volumes


