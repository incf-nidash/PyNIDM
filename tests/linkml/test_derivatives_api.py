# 4. Leading-zero-tolerant cross-graph join
# ---------------------------------------------------------------------------


def test_leading_zero_join():
    measures = {"BrainSegVol": 999999}
    cde = _build_cde(measures)

    # Derivative subject is zero-padded; experiment subject is not.
    derivative_graph = add_segmentation_derivative(
        subject_id="0051456",
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=cde,
        nidm_file=None,
    )
    experiment_graph = _experiment_graph(subject_id="51456", age=30)

    uber = _uber_graph(derivative_graph, experiment_graph)
    rows = list(uber.query(_JOIN_QUERY))

    assert rows, "leading-zero join returned no rows"
    ids = {str(r["ID"]) for r in rows}
    volumes = {int(r["volume"]) for r in rows}
    # The experiment subject id (un-padded) is what comes back.
    assert ids == {"51456"}
    assert 999999 in volumes


# ---------------------------------------------------------------------------
# 5. GetBrainVolumes (`pynidm query -bv`) tool binding
# ---------------------------------------------------------------------------
#
# GetBrainVolumes finds the producing tool via
#   prov:qualifiedAssociation [prov:agent [nidm:NIDM_0000164 ?tool]]
# i.e. nidm:NIDM_0000164 must be a PREDICATE on the SoftwareAgent (as in the
# ds002411 FreeSurfer graph: `nidm:NIDM_0000164 fs:`), NOT merely an
# association hadRole.  Without it the derivative is invisible to -bv.

# The exact tool-binding clause GetBrainVolumes uses, applied against the
# derivative's own subject Person (standalone graph carries ndar:src_subject_id).
_GBV_QUERY = """
    prefix rdf:  <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
    prefix prov: <http://www.w3.org/ns/prov#>
    prefix ndar: <https://ndar.nih.gov/api/datadictionary/v2/dataelement/>
    prefix nidm: <http://purl.org/nidash/nidm#>
    prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>

    select distinct ?ID ?tool ?softwareLabel ?volume where {
        ?tool_act a prov:Activity ;
                  prov:qualifiedAssociation [prov:agent [nidm:NIDM_0000164 ?tool]] .
        ?tool_act prov:qualifiedAssociation [prov:agent [ndar:src_subject_id ?ID]] .
        ?tool_entity prov:wasGeneratedBy ?tool_act ;
                     ?measure ?volume .
        ?measure a/rdfs:subClassOf* nidm:DataElement ;
                 rdfs:label ?softwareLabel ;
                 nidm:measureOf <http://uri.interlex.org/base/ilx_0112559> ;
                 nidm:datumType <http://uri.interlex.org/base/ilx_0738276> .
    }
"""


def test_software_agent_carries_tool_binding():
    """The SoftwareAgent must carry `nidm:NIDM_0000164 <tool-uri>` as a
    predicate (not just an association role) so GetBrainVolumes can bind ?tool."""
    measures = {"BrainSegVol": 1200000}
    graph = add_segmentation_derivative(
        subject_id="0050002",
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=_build_cde(measures),
        nidm_file=None,
    )
    agent = _one(graph.subjects(RDF.type, NIDM["SoftwareAgent"]))
    assert (agent, NIDM["NIDM_0000164"], URIRef(SOFTWARE_URL)) in graph


def test_getbrainvolumes_pattern_returns_tool_and_volume():
    """The full GetBrainVolumes tool-binding pattern resolves against a
    standalone derivative graph: ?tool, ?ID and ?volume all bind."""
    measures = {"Left-Hippocampus": 3500.0, "BrainSegVol": 1200000}
    graph = add_segmentation_derivative(
        subject_id="0050002",
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=_build_cde(measures),
        nidm_file=None,
    )
    rows = list(graph.query(_GBV_QUERY))
    assert rows, "GetBrainVolumes tool-binding pattern returned no rows"
    tools = {str(r["tool"]) for r in rows}
    ids = {str(r["ID"]) for r in rows}
    volumes = {float(r["volume"]) for r in rows}
    assert tools == {SOFTWARE_URL}
    assert ids == {"0050002"}
    assert 1200000 in volumes


def test_merge_cde_false_omits_cde_definitions():
    """merge_cde=False still attaches values via the CDE URI predicate, but
    does NOT copy the CDE definition triples into the output graph."""
    measures = {"BrainSegVol": 1200000}
    cde = _build_cde(measures)
    graph = add_segmentation_derivative(
        subject_id="01",
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=cde,
        nidm_file=None,
        merge_cde=False,
    )
    cde_uri = URIRef(SOFTWARE_URL + "BrainSegVol")
    der_obj = _one(graph.subjects(RDF.type, NIDM["DerivativeObject"]))
    # value still attached using the CDE URI as predicate
    assert graph.value(subject=der_obj, predicate=cde_uri) is not None
    # but the CDE DEFINITION triples are absent (written separately)
    assert (cde_uri, NIDM["measureOf"], ILX_VOLUME) not in graph
    assert (cde_uri, RDF.type, NIDM["DataElement"]) not in graph


def test_getbrainvolumes_end_to_end(tmp_path: Path):
    """Serialize a standalone derivative and run the REAL GetBrainVolumes
    query function over the file -- the -bv command path."""
    from nidm.linkml.experiment.query import GetBrainVolumes

    measures = {"BrainSegVol": 1200000}
    out = tmp_path / "seg.ttl"
    add_segmentation_derivative(
        subject_id="0050002",
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=_build_cde(measures),
        nidm_file=None,
        output_file=str(out),
    )
    df = GetBrainVolumes(str(out))
    assert df is not None and len(df) >= 1, "GetBrainVolumes returned no rows"
    # tool and volume made it into the dataframe
    joined = " ".join(str(v) for v in df.to_numpy().flatten())
    assert SOFTWARE_URL in joined
    assert "1200000" in joined
