"""
Tests for the public ``add_segmentation_derivative`` ingestion API
(``nidm.linkml.experiment.derivatives``).

These prove the FSL/FS/ANTs ingesters get a derivative model identical to
``csv2nidm -derivative``:

  * ``test_standalone_emits_correct_model`` -- a standalone graph carries
    exactly one Derivative / DerivativeObject (typed DerivativeCollection),
    one SoftwareAgent, cmdline/platform on the activity, a Person with
    ndar:src_subject_id, and the measure values on the DerivativeObject.
  * ``test_add_to_existing_attaches_to_person`` -- appending to an
    existing NIDM file wires the subject association to the EXISTING
    Person (no duplicate minted).
  * ``test_cross_graph_join`` -- a standalone derivative graph + a
    separate experiment graph, loaded together, join the measure back to
    the experiment subject via ndar:src_subject_id.
  * ``test_leading_zero_join`` -- the same join tolerates zero-padding
    differences ("0051456" vs "51456"), mirroring the query layer.
"""
from __future__ import annotations
from pathlib import Path
from rdflib import Graph, Literal, URIRef
from rdflib.namespace import RDF, RDFS, XSD
from nidm.linkml.core.namespaces import DCT, DCTYPES, NDAR, NIDM, PROV, SIO
from nidm.linkml.experiment import Person, Project
from nidm.linkml.experiment.derivatives import add_segmentation_derivative

# InterLex URIs the GetBrainVolumes join keys on (volume measure + scalar
# datum type).
ILX_VOLUME = URIRef("http://uri.interlex.org/base/ilx_0112559")
ILX_SCALAR = URIRef("http://uri.interlex.org/base/ilx_0738276")

SOFTWARE_URL = "http://surfer.nmr.mgh.harvard.edu/"

SOFTWARE_METADATA = {
    "title": "FreeSurfer",
    "description": "Cortical reconstruction and volumetric segmentation",
    "version": "7.4.1",
    "url": SOFTWARE_URL,
    "cmdline": "recon-all -subjid sub-01 -all",
    "platform": "Linux-5.15.0-x86_64",
}


def _build_cde(measures: dict) -> Graph:
    """Build a minimal CDE graph for *measures* mirroring a real fs/fsl/ants
    CDE: each data element is a ``nidm:DataElement`` carrying an
    ``nidm:sourceVariable`` (what ``add_attributes_with_cde`` matches on)
    plus the ``rdfs:label`` / ``nidm:measureOf`` / ``nidm:datumType`` that
    ``GetBrainVolumes`` joins against.  Returns ``(graph)``; the CDE URIs
    live in the software's namespace, as csv2nidm mints them."""
    cde = Graph()
    for variable in measures:
        cde_uri = URIRef(SOFTWARE_URL + variable)
        cde.add((cde_uri, RDF.type, NIDM["DataElement"]))
        cde.add((cde_uri, NIDM["sourceVariable"], Literal(variable)))
        cde.add((cde_uri, RDFS.label, Literal(variable)))
        cde.add((cde_uri, NIDM["measureOf"], ILX_VOLUME))
        cde.add((cde_uri, NIDM["datumType"], ILX_SCALAR))
    return cde


def _one(subjects) -> URIRef:
    """Return the single element of *subjects*, asserting there is exactly one."""
    items = list(subjects)
    assert len(items) == 1, f"expected exactly one, got {len(items)}: {items}"
    return items[0]


# ---------------------------------------------------------------------------
# 1. Standalone graph model
# ---------------------------------------------------------------------------


def test_standalone_emits_correct_model(tmp_path: Path):
    subject_id = "0050002"
    measures = {
        "Left-Hippocampus": 3500.0,
        "Right-Hippocampus": 3600.0,
        "BrainSegVol": 1200000,
    }
    cde = _build_cde(measures)

    out = tmp_path / "seg.ttl"
    graph = add_segmentation_derivative(
        subject_id=subject_id,
        software_metadata=SOFTWARE_METADATA,
        measures=measures,
        cde=cde,
        nidm_file=None,
        source_url="http://example.org/derivatives/sub-01/stats",
        output_file=str(out),
    )

    # Exactly one Derivative activity.
    der = _one(graph.subjects(RDF.type, NIDM["Derivative"]))

    # Exactly one DerivativeObject, also typed nidm:DerivativeCollection.
    der_obj = _one(graph.subjects(RDF.type, NIDM["DerivativeObject"]))
    assert (der_obj, RDF.type, NIDM["DerivativeCollection"]) in graph
    # The object was generated by the derivative activity.
    assert (der_obj, PROV.wasGeneratedBy, der) in graph

    # Exactly one SoftwareAgent carrying title / version / url.
    agent = _one(graph.subjects(RDF.type, NIDM["SoftwareAgent"]))
    assert (agent, DCTYPES.title, Literal("FreeSurfer")) in graph
    assert (agent, DCT.hasVersion, Literal("7.4.1")) in graph
    assert (agent, SIO.URL, Literal(SOFTWARE_URL)) in graph

    # cmdline + platform on the Derivative ACTIVITY, keyed by software url.
    assert (
        der,
        URIRef(SOFTWARE_URL + "cmdline"),
        Literal(SOFTWARE_METADATA["cmdline"]),
    ) in graph
    assert (
        der,
        URIRef(SOFTWARE_URL + "platform"),
        Literal(SOFTWARE_METADATA["platform"]),
    ) in graph

    # A Person carrying ndar:src_subject_id == subject_id.
    person = _one(graph.subjects(RDF.type, PROV.Person))
    assert (person, NDAR["src_subject_id"], Literal(subject_id)) in graph

    # The subject association links the derivative to that Person with role
    # sio:Subject.
    subj_agents = set()
    for assoc in graph.objects(der, PROV.qualifiedAssociation):
        if SIO.Subject in set(graph.objects(assoc, PROV.hadRole)):
            subj_agents.update(graph.objects(assoc, PROV.agent))
    assert person in subj_agents

    # The measure values are attached to the DerivativeObject via the CDE URIs.
    for variable, value in measures.items():
        cde_uri = URIRef(SOFTWARE_URL + variable)
        obj = graph.value(subject=der_obj, predicate=cde_uri)
        assert obj is not None, f"missing measure {variable}"
        assert float(obj.toPython()) == float(value)

    # source_url landed as a prov:Location xsd:anyURI literal, as given.
    loc = graph.value(subject=der_obj, predicate=PROV.Location)
    assert isinstance(loc, Literal) and loc.datatype == XSD.anyURI

    # File was serialized.
    assert out.exists()


